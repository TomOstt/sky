//! The tables, the Markdown report and the generated interpretation.
//!
//! Nothing here is hand-written per run: the interpretation is assembled from
//! the measured numbers (who beat whom, by how much) plus fixed explanations
//! of the mechanisms behind each kind of workload, so a re-run regenerates it.

use std::fmt::Write;

use super::workloads::Kind;
use super::{is_sky_engine, CaseResult, Outcome, Run, IMPLS};

/// The references Sky is compared against, in report order: id and label.
const REFS: [(&str, &str); 5] = [
    ("c", "C -O3"),
    ("rust", "Rust -O3"),
    ("lib", "the BLAS/LAPACK library"),
    ("python", "CPython"),
    ("numpy", "NumPy"),
];

fn label(id: &str) -> &'static str {
    IMPLS.iter().find(|(i, _)| *i == id).map_or("?", |(_, l)| l)
}

/// The report as printed to the terminal: the same Markdown.
pub fn terminal(run: &Run) -> String {
    markdown(run)
}

/// A time in ns as `12.3 ms`, or seconds from 10 s up.
pub fn fmt_time(ns: f64) -> String {
    let ms = ns / 1e6;
    if ms >= 10_000.0 {
        format!("{:.1} s", ms / 1e3)
    } else if ms >= 100.0 {
        format!("{ms:.0} ms")
    } else if ms >= 10.0 {
        format!("{ms:.1} ms")
    } else {
        format!("{ms:.2} ms")
    }
}

/// A ratio as `12.3x`; bold when it is below 1 (Sky faster).
fn fmt_ratio(r: f64) -> String {
    let text = if r >= 100.0 {
        format!("{r:.0}x")
    } else if r >= 10.0 {
        format!("{r:.1}x")
    } else {
        format!("{r:.2}x")
    };
    if r < 1.0 {
        format!("**{text}**")
    } else {
        text
    }
}

fn table(header: &[String], rows: &[Vec<String>]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "| {} |", header.join(" | "));
    let _ = writeln!(
        out,
        "|{}|",
        header
            .iter()
            .enumerate()
            .map(|(i, _)| if i == 0 { "---" } else { "---:" })
            .collect::<Vec<_>>()
            .join("|")
    );
    for r in rows {
        let _ = writeln!(out, "| {} |", r.join(" | "));
    }
    out
}

/// Implementations with anything to show (something ran or failed).
fn columns(run: &Run) -> Vec<&'static str> {
    IMPLS
        .iter()
        .map(|(id, _)| *id)
        .filter(|id| {
            run.cases
                .iter()
                .any(|c| matches!(c.cell(id), Some(Outcome::Ran(_) | Outcome::Failed(_))))
        })
        .collect()
}

/// The Sky engines that ran anywhere.
fn sky_columns(run: &Run) -> Vec<&'static str> {
    columns(run)
        .into_iter()
        .filter(|id| is_sky_engine(id))
        .collect()
}

/// The fastest Sky engine that ran and agrees with the reference.
fn best_sky(c: &CaseResult) -> Option<(&'static str, f64)> {
    c.cells
        .iter()
        .filter(|(id, _)| is_sky_engine(id))
        .filter_map(|(id, _)| c.time(id).map(|t| (*id, t)))
        .min_by(|a, b| a.1.total_cmp(&b.1))
}

fn geomean(xs: &[f64]) -> f64 {
    (xs.iter().map(|x| x.ln()).sum::<f64>() / xs.len() as f64).exp()
}

fn median(xs: &mut [f64]) -> f64 {
    xs.sort_by(f64::total_cmp);
    let n = xs.len();
    if n % 2 == 1 {
        xs[n / 2]
    } else {
        (xs[n / 2 - 1] + xs[n / 2]) / 2.0
    }
}

/// The full Markdown report.
pub fn markdown(run: &Run) -> String {
    let mut o = String::new();
    let _ = writeln!(
        o,
        "# Sky against C, Rust, Python and hand-tuned libraries\n"
    );
    let _ = writeln!(
        o,
        "_Generated by `cargo run --release -p sky-bench -- compare`. Do not edit by hand: the next run overwrites this file._\n"
    );
    if run.opts.quick {
        let _ = writeln!(
            o,
            "**This is a `--quick` run at tiny sizes: the numbers mean nothing.**\n"
        );
    }
    machine_section(&mut o, run);
    method_section(&mut o, run);
    results_section(&mut o, run);
    ratio_sections(&mut o, run);
    notes_section(&mut o, run);
    let _ = writeln!(o, "## Interpretation\n");
    let _ = writeln!(
        o,
        "_Assembled from the numbers above by the harness. The explanations name known mechanisms of each engine; they are not profiler output._\n"
    );
    for line in interpretation(run) {
        let _ = writeln!(o, "- {line}");
    }
    o
}

fn machine_section(o: &mut String, run: &Run) {
    let m = &run.machine;
    let _ = writeln!(o, "## Machine\n");
    let _ = writeln!(o, "- CPU: {} ({})", m.cpu, m.arch);
    let _ = writeln!(o, "- Cores: {}", m.cores);
    let _ = writeln!(o, "- Memory: {}", m.memory);
    let _ = writeln!(o, "- OS: {}", m.os);
    if let (Some(a), Some(b)) = (run.load.0, run.load.1) {
        let cores = std::thread::available_parallelism().map_or(1, |n| n.get());
        let _ = writeln!(o, "- Load average (1 min) when the measurements started / ended: {a:.1} / {b:.1} on {cores} logical cores");
        if a.max(b) > cores as f64 * 0.5 {
            let _ = writeln!(o, "- **Warning: the machine was busy while this ran, so timings are inflated and noisy (see the spreads); re-run on an idle machine before trusting a ratio.**");
        }
    }
    if let Some(d) = &run.date {
        let _ = writeln!(o, "- Date (UTC): {d}");
    }
    if let Some(r) = &run.rev {
        let _ = writeln!(o, "- Sky revision: `{r}`");
    }
    let _ = writeln!(o, "\n### Toolchains\n");
    let t = &run.tools;
    let item = |o: &mut String, name: &str, v: Option<String>| match v {
        Some(v) => {
            let _ = writeln!(o, "- {name}: {v}");
        }
        None => {
            let _ = writeln!(o, "- {name}: not found (column skipped)");
        }
    };
    item(
        o,
        "C compiler",
        t.c.as_ref().map(|c| {
            format!(
                "{} (`-O3 -march=native`, and with `-ffast-math`)",
                c.version
            )
        }),
    );
    item(
        o,
        "Rust",
        t.rust
            .as_ref()
            .map(|r| format!("{} (`-C opt-level=3 -C target-cpu=native`)", r.version)),
    );
    item(
        o,
        "Python",
        t.python
            .as_ref()
            .map(|p| format!("{} (pure CPython)", p.version)),
    );
    item(o, "NumPy", t.numpy.clone());
    item(o, "BLAS/LAPACK", t.lib.clone());
    item(
        o,
        "Sky",
        t.sky.as_ref().map(|_| {
            format!(
                "release build of `sky run`; engines present: {}{}",
                if t.engines.is_empty() {
                    "none".to_string()
                } else {
                    t.engines.join(", ")
                },
                if t.missing_engines.is_empty() {
                    String::new()
                } else {
                    format!(
                        "; not present in this build: {}",
                        t.missing_engines.join(", ")
                    )
                }
            )
        }),
    );
    let _ = writeln!(o);
}

fn method_section(o: &mut String, run: &Run) {
    let _ = writeln!(o, "## Method\n");
    let _ = writeln!(
        o,
        "- Each cell is a separate program run as a subprocess: {} untimed warmup run(s), then {} timed repetitions; the table shows the **median wall time** and, in parentheses, the **spread** (max - min) / median. A `†` marks a cell whose first run took more than {} s and was measured once.",
        run.opts.warmup,
        run.opts.reps,
        run.opts.slow.as_secs()
    );
    let _ = writeln!(
        o,
        "- Wall time includes process start-up and, for Sky, lexing, parsing, checking and lowering. The fixed part is in the floors below."
    );
    if let Some(n) = run.opts.threads {
        let _ = writeln!(
            o,
            "- Every Sky run used `--threads={n}` (automatic parallelism: big kernels in chunks, independent calls on workers; the output does not depend on it)."
        );
    }
    let _ = writeln!(
        o,
        "- All implementations build the same deterministic inputs and print the result on the last line; a cell whose numbers differ from the reference (the first implementation that ran, normally C) by more than the workload's relative tolerance is marked `!` and left out of every ratio."
    );
    let _ = writeln!(
        o,
        "- Sources: `benches/compare/{{sky,c,rust,python,numpy,lib}}`. Sizes are `--quick`-scalable; the report is only written for a full, unfiltered run."
    );
    let _ = writeln!(o, "\n### Floors (an empty program)\n");
    let f = &run.floors;
    if let Some(ns) = f.c_ns {
        let _ = writeln!(o, "- empty C process: {}", fmt_time(ns as f64));
    }
    if let Some(ns) = f.python_ns {
        let _ = writeln!(o, "- `python3 -c pass`: {}", fmt_time(ns as f64));
    }
    for (e, ns) in &f.sky_ns {
        let _ = writeln!(
            o,
            "- `sky run --engine={e}` on `print(1)`: {}",
            fmt_time(*ns as f64)
        );
    }
    let _ = writeln!(o);
    let _ = writeln!(o, "### Workloads\n");
    let rows: Vec<Vec<String>> = run
        .cases
        .iter()
        .map(|c| {
            vec![
                format!("`{}`", c.case.id),
                c.case.title.clone(),
                if c.case.tolerance == 0.0 {
                    "exact".to_string()
                } else {
                    format!("{:e}", c.case.tolerance)
                },
            ]
        })
        .collect();
    let _ = writeln!(
        o,
        "{}",
        table(&["case".into(), "what".into(), "tolerance".into()], &rows)
    );
}

/// Footnotes for failed cells, numbered in order of appearance.
fn footnotes(run: &Run) -> Vec<String> {
    let mut notes: Vec<String> = Vec::new();
    for c in &run.cases {
        for (id, out) in &c.cells {
            if let Outcome::Failed(why) = out {
                let text = format!("{} on `{}`: {why}", label(id), c.case.id);
                if !notes.contains(&text) {
                    notes.push(text);
                }
            }
        }
    }
    notes
}

fn results_section(o: &mut String, run: &Run) {
    let cols = columns(run);
    let notes = footnotes(run);
    let _ = writeln!(o, "## Results: median wall time (spread)\n");
    let mut header = vec!["case".to_string()];
    header.extend(cols.iter().map(|c| label(c).to_string()));
    let rows: Vec<Vec<String>> = run
        .cases
        .iter()
        .map(|c| {
            let mut row = vec![format!("`{}`", c.case.id)];
            for id in &cols {
                row.push(match c.cell(id) {
                    Some(Outcome::Ran(r)) => {
                        let spread = r.stats.spread_percent();
                        format!(
                            "{} ({spread:.0}%){}{}",
                            fmt_time(r.stats.median as f64),
                            if r.single { " †" } else { "" },
                            if r.mismatch.is_some() { " !" } else { "" }
                        )
                    }
                    Some(Outcome::Failed(why)) => {
                        let text = format!("{} on `{}`: {why}", label(id), c.case.id);
                        let n = notes.iter().position(|t| *t == text).map_or(0, |p| p + 1);
                        format!("fails [{n}]")
                    }
                    _ => "-".to_string(),
                });
            }
            row
        })
        .collect();
    let _ = writeln!(o, "{}", table(&header, &rows));
    let _ = writeln!(
        o,
        "`-` means not run (tool or program missing); `fails [n]` is explained under Notes.\n"
    );
}

fn ratio_sections(o: &mut String, run: &Run) {
    let sky = sky_columns(run);
    if sky.is_empty() {
        return;
    }
    let _ = writeln!(o, "## Ratios: Sky time / other time\n");
    let _ = writeln!(
        o,
        "Above 1 means Sky is slower than the reference; **bold** means Sky is faster. Medians of wall time, so they include the floors above.\n"
    );
    for (rid, rlabel) in REFS {
        let rows_for: Vec<&CaseResult> =
            run.cases.iter().filter(|c| c.time(rid).is_some()).collect();
        if rows_for.is_empty() {
            continue;
        }
        let _ = writeln!(o, "### Against {rlabel}\n");
        let mut header = vec!["case".to_string()];
        header.extend(sky.iter().map(|s| label(s).to_string()));
        header.push("best Sky".to_string());
        let rows: Vec<Vec<String>> = rows_for
            .iter()
            .map(|c| {
                let base = c.time(rid).unwrap_or(f64::NAN);
                let mut row = vec![format!("`{}`", c.case.id)];
                for s in &sky {
                    row.push(match c.time(s) {
                        Some(t) => fmt_ratio(t / base),
                        None => "n/a".to_string(),
                    });
                }
                row.push(match best_sky(c) {
                    Some((_, t)) => fmt_ratio(t / base),
                    None => "n/a".to_string(),
                });
                row
            })
            .collect();
        let _ = writeln!(o, "{}", table(&header, &rows));
    }
    // C with fast-math as a labelled row of its own.
    let fast: Vec<&CaseResult> = run
        .cases
        .iter()
        .filter(|c| c.time("c-fast").is_some())
        .collect();
    if !fast.is_empty() {
        let _ = writeln!(o, "### Against C with -ffast-math (different semantics: it may reassociate, fuse and assume no NaN/inf)\n");
        let mut header = vec!["case".to_string()];
        header.extend(sky.iter().map(|s| label(s).to_string()));
        let rows: Vec<Vec<String>> = fast
            .iter()
            .map(|c| {
                let base = c.time("c-fast").unwrap_or(f64::NAN);
                let mut row = vec![format!("`{}`", c.case.id)];
                for s in &sky {
                    row.push(c.time(s).map_or("n/a".to_string(), |t| fmt_ratio(t / base)));
                }
                row
            })
            .collect();
        let _ = writeln!(o, "{}", table(&header, &rows));
    }
}

fn notes_section(o: &mut String, run: &Run) {
    let notes = footnotes(run);
    let mismatches: Vec<String> = run
        .cases
        .iter()
        .flat_map(|c| {
            c.cells.iter().filter_map(move |(id, out)| match out {
                Outcome::Ran(r) => r
                    .mismatch
                    .as_ref()
                    .map(|m| format!("{} on `{}`: {m}", label(id), c.case.id)),
                _ => None,
            })
        })
        .collect();
    if notes.is_empty() && mismatches.is_empty() {
        return;
    }
    let _ = writeln!(o, "## Notes\n");
    for (i, n) in notes.iter().enumerate() {
        let _ = writeln!(o, "{}. {n}", i + 1);
    }
    for m in &mismatches {
        let _ = writeln!(o, "- **Result mismatch** (`!`): {m}");
    }
    let _ = writeln!(o);
}

/// How a kind of workload behaves on Sky's engines, and why it loses.
fn loss_reason(kind: Kind) -> &'static str {
    match kind {
        Kind::Calls => "function-call-heavy code: every call is interpreted (argument passing, a frame, an overflow/finiteness check on each add), while C and Rust compile the recursion to a few instructions and LLVM rewrites part of it into a loop",
        Kind::Scalar => "scalar-heavy loops: each operation is dispatched by an interpreter and its result checked to be finite (Sky never produces a silent inf or NaN), while a compiled loop keeps the values in registers; reproducible mode also forbids the fused multiply-add and reassociation that `-O3 -march=native`, and `-ffast-math` even more, are free to use",
        Kind::SmallVector => "2 and 3-element vectors in a loop: each vector operation allocates a small array and checks every element, where C and Rust keep the components in registers and unroll",
        Kind::ArrayChain => "elementwise chains: arrays are immutable, so an unfused operation allocates a new array and makes its own pass over memory (finiteness-checked), where C makes one fused pass; the `fuse` pass turns a chain into one kernel, but Sky's time here also includes building the inputs from outer products (`@`) and the front end's work on the large literals, which the C and Rust programs do not pay",
        Kind::Matmul => "dense matmul: Sky's `@` is a plain loop inside the interpreter's runtime, not a cache-blocked SIMD kernel, so it trails vectorised C and is far behind a vendor BLAS",
        Kind::Cholesky => "Cholesky: an unblocked factorisation with finiteness checks, against a blocked LAPACK `dpotrf` on the library side",
    }
}

/// Why Sky can win, per kind (used only when the numbers show a win).
fn win_reason(kind: Kind) -> &'static str {
    match kind {
        Kind::Calls | Kind::Scalar => "the compiled row it beat here is the interpreted one (CPython): Sky's engines run on unboxed `f64`s with types and units resolved before the run, while CPython boxes every float and dispatches every operation dynamically",
        Kind::SmallVector => "against CPython, which boxes every float and dispatches every operation, an interpreter that resolves types and units ahead of the run pays less per operation",
        Kind::ArrayChain => "whole-array operations run in compiled Rust routines inside the interpreter, so on large arrays the interpreter overhead is amortised and Sky behaves like a native loop plus an allocation per operation, which beats a pure-Python loop by a wide margin",
        Kind::Matmul => "`@` runs as a compiled loop inside the runtime, so it is not paying interpreter overhead per multiply-add, unlike a pure-Python triple loop",
        Kind::Cholesky => "`K⁻¹ @ f` on a positive definite `K` is rewritten to a Cholesky solve (factor plus two triangular solves, about n^3/3 flops) instead of forming an inverse (about n^3): that is the same algorithm the C, Rust and library rows use, so against them it is parity of algorithm, not an edge; against code that forms the inverse it would save about a factor of 3 in flops, which this run did not measure",
    }
}

/// The generated interpretation, one bullet per finding.
pub fn interpretation(run: &Run) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let sky = sky_columns(run);
    if sky.is_empty() {
        out.push("No Sky engine ran in this run, so there is nothing to compare; the other columns are still valid measurements of the baselines.".to_string());
        return out;
    }

    // 1. The headline per reference.
    for (rid, rlabel) in REFS {
        let pairs: Vec<(&CaseResult, f64)> = run
            .cases
            .iter()
            .filter_map(|c| {
                let base = c.time(rid)?;
                let (_, t) = best_sky(c)?;
                Some((c, t / base))
            })
            .collect();
        if pairs.is_empty() {
            continue;
        }
        let ratios: Vec<f64> = pairs.iter().map(|p| p.1).collect();
        let wins = ratios.iter().filter(|r| **r < 1.0).count();
        let (lo, hi) = ratios.iter().fold((f64::INFINITY, 0.0f64), |(lo, hi), r| {
            (lo.min(*r), hi.max(*r))
        });
        let g = geomean(&ratios);
        let mut line = format!(
            "**Against {rlabel}** ({} cases where both ran): Sky's best engine was faster in {wins} and slower in {}; the geometric-mean ratio is {} (Sky time / {rlabel} time; range {} to {}).",
            pairs.len(),
            pairs.len() - wins,
            fmt_ratio(g).replace("**", ""),
            fmt_ratio(lo).replace("**", ""),
            fmt_ratio(hi).replace("**", ""),
        );
        if rid == "lib" {
            let within = ratios.iter().filter(|r| **r <= 2.0).count();
            line.push_str(&format!(
                " Phase 4's target is within 2x of the hand-tuned library: met in {within} of {}.",
                pairs.len()
            ));
        }
        out.push(line);
    }

    // 2. Where Sky wins.
    // (kind, example case, whether the win was over a compiled baseline)
    let mut wins: Vec<(Kind, String, bool)> = Vec::new();
    let mut any_compiled_win = false;
    for (rid, rlabel) in REFS {
        let mut list: Vec<String> = Vec::new();
        for c in &run.cases {
            if let (Some(base), Some((eng, t))) = (c.time(rid), best_sky(c)) {
                if t < base {
                    list.push(format!(
                        "`{}` ({}, {})",
                        c.case.id,
                        label(eng),
                        fmt_ratio(t / base).replace("**", "")
                    ));
                    let compiled = rid != "python" && rid != "numpy";
                    if !wins
                        .iter()
                        .any(|(k, _, cm)| *k == c.case.kind && *cm == compiled)
                    {
                        wins.push((c.case.kind, c.case.id.clone(), compiled));
                    }
                    if compiled {
                        any_compiled_win = true;
                    }
                }
            }
        }
        if !list.is_empty() {
            out.push(format!(
                "**Sky was faster than {rlabel} on:** {}.",
                list.join(", ")
            ));
        }
    }
    if !any_compiled_win {
        out.push("**Sky did not beat compiled C, compiled Rust or the hand-tuned library on any workload in this run.** Any claim that it is faster than them is unsupported by these numbers.".to_string());
    }
    for (kind, example, compiled) in &wins {
        if *compiled {
            out.push(format!(
                "Sky beat a compiled baseline on a {kind:?} workload (`{example}`). This harness cannot say why from the numbers alone; the likely candidates are that the C and Rust rows are plain source, not hand-vectorised or hand-blocked code, and that a fixed cost dominates a short run. Check that cell's spread and the floors before trusting it."
            ));
        } else {
            out.push(format!(
                "Why Sky beats CPython on {kind:?} workloads (for example `{example}`): {}.",
                win_reason(*kind)
            ));
        }
    }

    // 3. Where it loses.
    let mut gaps: Vec<(&CaseResult, f64, &str)> = Vec::new();
    for c in &run.cases {
        for (rid, rlabel) in [("c", "C -O3"), ("rust", "Rust -O3")] {
            if let (Some(base), Some((_, t))) = (c.time(rid), best_sky(c)) {
                gaps.push((c, t / base, rlabel));
                break;
            }
        }
    }
    gaps.sort_by(|a, b| b.1.total_cmp(&a.1));
    let worst: Vec<String> = gaps
        .iter()
        .take(3)
        .filter(|g| g.1 > 1.0)
        .map(|(c, r, l)| format!("`{}` ({}, against {l})", c.case.id, fmt_ratio(*r)))
        .collect();
    if !worst.is_empty() {
        out.push(format!(
            "**Largest gaps to compiled code (best Sky engine):** {}.",
            worst.join(", ")
        ));
    }
    let mut seen: Vec<Kind> = Vec::new();
    for (c, r, _) in gaps.iter().filter(|g| g.1 > 1.0) {
        if !seen.contains(&c.case.kind) {
            seen.push(c.case.kind);
            out.push(format!(
                "Why Sky loses on {:?} workloads (worst here: `{}` at {}): {}.",
                c.case.kind,
                c.case.id,
                fmt_ratio(*r),
                loss_reason(c.case.kind)
            ));
        }
    }

    // 4. Engines.
    if sky.contains(&"sky-ast") && sky.contains(&"sky-sir") {
        let mut r: Vec<f64> = run
            .cases
            .iter()
            .filter_map(|c| Some(c.time("sky-sir")? / c.time("sky-ast")?))
            .collect();
        if !r.is_empty() {
            let faster = r.iter().filter(|x| **x < 1.0).count();
            let n = r.len();
            let m = median(&mut r);
            out.push(format!(
                "**Engines:** `sir` was faster than `ast` in {faster} of {n} cases (median sir/ast time ratio {}).",
                fmt_ratio(m).replace("**", "")
            ));
        }
    }
    if !run.tools.missing_engines.is_empty() && !run.opts.quick {
        out.push(format!(
            "Engines not present in this build, so not measured: {}.",
            run.tools.missing_engines.join(", ")
        ));
    }
    let failed: Vec<String> = footnotes(run);
    if !failed.is_empty() {
        out.push(format!(
            "**{} cell(s) did not run** (see Notes): Sky rejects or cannot yet execute those programs, so nothing is claimed about them.",
            failed.len()
        ));
    }

    // 5. Where the floor decides.
    if let Some(floor) = run.floors.c_ns {
        let near: Vec<String> = run
            .cases
            .iter()
            .filter(|c| {
                ["c", "rust", "lib"]
                    .iter()
                    .filter_map(|id| c.time(id))
                    .fold(f64::INFINITY, f64::min)
                    < 3.0 * floor as f64
            })
            .map(|c| format!("`{}`", c.case.id))
            .collect();
        if !near.is_empty() && !run.opts.quick {
            out.push(format!(
                "**Ratios are floor-limited** where the fastest baseline takes under 3x an empty process ({}): {}. There the ratio measures start-up and the front end as much as the computation.",
                fmt_time(floor as f64),
                near.join(", ")
            ));
        }
    }

    // 5b. Fixed costs of the Sky engines themselves.
    if let Some(min) = run.floors.sky_ns.iter().map(|(_, n)| *n).min() {
        let heavy: Vec<String> = run
            .floors
            .sky_ns
            .iter()
            .filter(|(_, n)| *n > 50_000_000 && *n > 5 * min)
            .map(|(e, n)| format!("`{e}` ({})", fmt_time(*n as f64)))
            .collect();
        if !heavy.is_empty() {
            out.push(format!(
                "**Fixed cost of Sky's engines:** an empty program (`print(1)`) takes {} on the fastest engine but far longer on {}. That start-up cost is paid on every run and is included in every Sky number above, so it decides the short cases.",
                fmt_time(min as f64),
                heavy.join(", ")
            ));
        }
    }

    // 6. What this does not show.
    out.push("**Assembly was not measured.** No hand-written assembly is part of this run; the vendor BLAS/LAPACK rows are the nearest measured proxy for hand-tuned code, and only for matmul and Cholesky. Nothing here supports or refutes a claim about assembly.".to_string());
    out.push("**Different guarantees.** Sky results are finite-checked, unit-checked and bit-reproducible (no fused multiply-add, no reassociation); the C and Rust rows give none of that, and the `-ffast-math` row deliberately gives up more. Faster or slower here is not the same contract.".to_string());
    out.push("**One machine, one run.** Medians of a handful of runs on a laptop-class machine; the spreads above say how noisy each cell was, and differences inside the spread mean nothing. Workload inputs are built from outer products (`COL @ ROW`, since arrays are immutable and Sky has no array constructor beyond literals, `zeros` and `identity`), which makes them dense but structured.".to_string());
    out
}

#[cfg(test)]
mod tests {
    use super::super::workloads::cases;
    use super::super::{Floors, Machine, Options, Ran, ToolInfo};
    use super::*;
    use crate::stats::Stats;
    use std::time::Duration;

    fn ran(ms: f64) -> Outcome {
        Outcome::Ran(Ran {
            stats: Stats::new(vec![(ms * 1e6) as u64; 3]),
            values: vec![1.0],
            single: false,
            mismatch: None,
        })
    }

    fn opts() -> Options {
        Options {
            filter: None,
            reps: 3,
            warmup: 1,
            quick: false,
            out: None,
            sky: None,
            build_sky: false,
            no_sky: false,
            timeout: Duration::from_secs(1),
            slow: Duration::from_secs(1),
            list: false,
            emit_sky: None,
            threads: None,
            dir: ".".into(),
        }
    }

    fn run_with(cells: Vec<(&'static str, Outcome)>, id: &str) -> Run {
        let case = cases().into_iter().find(|c| c.id == id).expect("case");
        Run {
            machine: Machine::default(),
            tools: ToolInfo {
                c: None,
                rust: None,
                python: None,
                numpy: None,
                lib: None,
                sky: None,
                engines: vec!["ast", "sir"],
                missing_engines: vec!["native"],
            },
            floors: Floors {
                c_ns: Some(5_000_000),
                python_ns: None,
                sky_ns: vec![],
            },
            cases: vec![CaseResult { case, cells }],
            opts: opts(),
            rev: Some("abc".into()),
            date: None,
            load: (Some(0.5), Some(0.6)),
        }
    }

    #[test]
    fn times_and_ratios_format() {
        assert_eq!(fmt_time(1.5e6), "1.50 ms");
        assert_eq!(fmt_time(25e6), "25.0 ms");
        assert_eq!(fmt_time(250e6), "250 ms");
        assert_eq!(fmt_time(12e9), "12.0 s");
        assert_eq!(fmt_ratio(0.5), "**0.50x**");
        assert_eq!(fmt_ratio(12.34), "12.3x");
        assert_eq!(fmt_ratio(1234.0), "1234x");
    }

    #[test]
    fn a_losing_sky_is_reported_as_losing() {
        let run = run_with(
            vec![
                ("c", ran(10.0)),
                ("python", ran(500.0)),
                ("sky-ast", ran(2000.0)),
                ("sky-sir", ran(3000.0)),
            ],
            "nbody",
        );
        let text = interpretation(&run).join("\n");
        assert!(text.contains("did not beat compiled C"), "{text}");
        assert!(
            text.contains("Largest gaps") && text.contains("`nbody`"),
            "{text}"
        );
        assert!(text.contains("Assembly was not measured"), "{text}");
        assert!(
            text.contains("`sir` was faster than `ast` in 0 of 1"),
            "{text}"
        );
        assert!(text.contains("native"), "{text}");
    }

    #[test]
    fn a_winning_sky_is_reported_with_the_kind_of_reason() {
        let run = run_with(
            vec![
                ("c", ran(500.0)),
                ("python", ran(9000.0)),
                ("sky-ast", ran(100.0)),
            ],
            "matmul-256",
        );
        let text = interpretation(&run).join("\n");
        assert!(
            text.contains("Sky was faster than C -O3 on:** `matmul-256`"),
            "{text}"
        );
        assert!(!text.contains("did not beat compiled C"), "{text}");
        assert!(text.contains("Why Sky beats CPython on Matmul"), "{text}");
    }

    #[test]
    fn the_markdown_has_every_section_and_flags_failures_and_mismatches() {
        let mut bad = Ran {
            stats: Stats::new(vec![1_000_000]),
            values: vec![2.0],
            single: true,
            mismatch: Some("differs".to_string()),
        };
        bad.single = true;
        let run = run_with(
            vec![
                ("c", ran(10.0)),
                ("rust", Outcome::Ran(bad)),
                (
                    "numpy",
                    Outcome::Skipped("numpy is not installed".to_string()),
                ),
                ("sky-ast", ran(20.0)),
                ("sky-sir", Outcome::Failed("cannot run on SIR".to_string())),
            ],
            "rk4",
        );
        let md = markdown(&run);
        for part in [
            "## Machine",
            "## Method",
            "## Results",
            "## Ratios",
            "### Against C -O3",
            "## Notes",
            "## Interpretation",
        ] {
            assert!(md.contains(part), "missing {part}\n{md}");
        }
        assert!(
            md.contains("fails [1]") && md.contains("1. Sky sir on `rk4`: cannot run on SIR"),
            "{md}"
        );
        assert!(
            md.contains("Result mismatch") && md.contains(" †") && md.contains(" !"),
            "{md}"
        );
        assert!(
            !md.contains("NumPy |"),
            "an all-skipped column is left out\n{md}"
        );
    }

    #[test]
    fn no_sky_means_a_plain_statement() {
        let mut run = run_with(vec![("c", ran(1.0))], "fib-30");
        run.tools.engines.clear();
        let text = interpretation(&run).join("\n");
        assert!(text.contains("No Sky engine ran"), "{text}");
        assert!(markdown(&run).contains("## Interpretation"));
    }
}
