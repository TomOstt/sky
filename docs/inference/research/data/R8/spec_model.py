#!/usr/bin/env python3
"""R8: speculative-decoding performance model for Qwen3-32B on an M5 Max-class GPU, plus MoE
expert-union arithmetic. Every input is a labeled assumption; see R8-algorithms.md section 2.
Run: python3 spec_model.py > spec_model.out.md
"""
import math

BW = 614e9            # B/s peak (Apple spec, M5 Max 40-core GPU)
EFF = 0.80            # assumed achieved fraction of peak for weight streaming (MLX-class kernel); placeholder
W = 17.99e9           # bytes streamed per Qwen3-32B decode token, MLX 4-bit g64 (model_math.py)
T1 = W / (BW * EFF)   # seconds per plain decode step

def E_tokens(alpha, gamma):
    """Leviathan et al. Eq. 1: expected tokens per round (chain draft of length gamma, i.i.d. acceptance alpha)."""
    if alpha >= 1: return gamma + 1
    return (1 - alpha ** (gamma + 1)) / (1 - alpha)

def alpha_from_tau(tau, gamma):
    lo, hi = 0.0, 0.9999
    for _ in range(100):
        mid = (lo + hi) / 2
        if E_tokens(mid, gamma) < tau: lo = mid
        else: hi = mid
    return (lo + hi) / 2

def speedup(tau, gamma, c, beta):
    """tau tokens per round; draft cost c*T1 per drafted token; verify cost T1*(1+beta*gamma)."""
    return tau / (1 + gamma * c + beta * gamma)

print("# R8 speculative-decoding model (generated by spec_model.py)\n")
print(f"Plain-decode step for Qwen3-32B 4-bit g64 at {EFF:.0%} of {BW/1e9:.0f} GB/s: T1 = {T1*1e3:.1f} ms -> {1/T1:.1f} tok/s.\n")

print("## A. Per-token acceptance alpha implied by published mean acceptance lengths (i.i.d. chain model)\n")
print("| source (target, temp) | k drafted | mean accepted length tau | implied alpha |")
print("|---|---|---|---|")
pub = [("RedHatAI Qwen3-32B EAGLE-3, HumanEval, T=0.6", 3, 2.29), ("same, HumanEval", 7, 2.53),
       ("same, GSM8K", 3, 2.49), ("same, GSM8K", 7, 3.08), ("same, CNN/DM", 3, 2.15), ("same, CNN/DM", 7, 2.33),
       ("AngelSlim Qwen3-32B EAGLE-3, MT-bench (H20, bs=1)", 2, 1.86), ("AngelSlim Qwen3-32B EAGLE-3, GSM8K", 2, 2.01),
       ("RedHatAI Qwen3-8B DFlash, HumanEval, T=0, think off", 15, 5.883), ("RedHatAI Qwen3.8-27B DSpark, HumanEval", 8, 4.42),
       ("RedHatAI Qwen3.8-27B DSpark, math", 8, 5.74), ("MTPLX Qwen3.6-27B MTP (per-position 73/48/32%)", 3, 2.53)]
for name, k, tau in pub:
    print(f"| {name} | {k} | {tau:.2f} | {alpha_from_tau(tau, k):.2f} |")
print("\nNote: per-position acceptance is not i.i.d. in practice (it decays with depth), so 'implied alpha' is only a summary.\n")

print("## B. Speedup S = tau / (1 + gamma*c + beta*gamma) for a chain draft\n")
print("c = draft cost per drafted token / T1; beta = marginal cost of verifying one more token / T1.")
print("beta ~0.02-0.05: kernel that streams weights once for M<=k* (target design); beta ~0.48: MLX 0.32 qmv at M=4 on M2 Pro (R3 measurement: 2.43x time for 4 rows).\n")
print("| tau source | gamma | c | beta=0.02 | beta=0.05 | beta=0.15 | beta=0.48 (MLX-like) |")
print("|---|---|---|---|---|---|---|")
for name, gamma, tau in [("Qwen3-32B EAGLE-3 HumanEval T=0.6", 3, 2.29), ("Qwen3-32B EAGLE-3 GSM8K T=0.6", 3, 2.49),
                         ("Qwen3-32B EAGLE-3 GSM8K T=0.6", 7, 3.08), ("Qwen3-32B EAGLE-3 CNN/DM T=0.6", 3, 2.15),
                         ("hypothetical tree, tau=3.5 (greedy code)", 15, 3.5), ("hypothetical tau=4.4 (DSpark-class)", 8, 4.42)]:
    for c in (0.03, 0.10):
        cells = [f"{speedup(tau, gamma, c, b):.2f}x ({speedup(tau, gamma, c, b)/T1:.0f} t/s)" for b in (0.02, 0.05, 0.15, 0.48)]
        print(f"| {name} | {gamma} | {c} | " + " | ".join(cells) + " |")

print("\n## C. 'Free' verification width k* on a bandwidth-bound GPU\n")
print("Weight-streaming matmul over k tokens: FLOPs = 2*N*k, bytes = N*b/8 -> intensity = 16k/b FLOP/byte.")
print("It stays bandwidth-bound while 16k/b < R = F/BW (ridge point), i.e. k* = R*b/16.\n")
print("| device / path | F (TFLOP/s) | BW (GB/s) | R=F/BW | k* at b=4.5 | k* at b=16 |")
print("|---|---|---|---|---|---|")
for name, F, bw in [("M5 Max NA fp16 (est. 70 TFLOPS, tzakharko)", 70, 614), ("M5 Max NA int8 (est. 130 TOPS)", 130, 614),
                    ("M5 Max SIMD fp32 (40c*128*2*1.6GHz)", 16.4, 614), ("M2 Pro SIMD fp32 (19c, ~6.8 TFLOPS)", 6.8, 200),
                    ("A100 fp16 tensor (312 TFLOPS, 2.0 TB/s)", 312, 2039)]:
    R = F * 1e12 / (bw * 1e9)
    print(f"| {name} | {F} | {bw} | {R:.0f} | {R*4.5/16:.1f} | {R:.0f} |")
print("\n(Sequoia's empirically optimal tree size on A100 with fp16 weights was 128; the formula gives ~153.)\n")

print("## D. MoE: distinct experts touched when verifying k tokens (independent routing = upper bound)\n")
print("| model | experts E | top-K | k=1 | k=2 | k=4 | k=8 | bytes(k=4)/bytes(k=1) | bytes(k=8)/bytes(k=1) |")
print("|---|---|---|---|---|---|---|---|---|")
# expert share of streamed bytes per token at 4-bit (model_math.py): Qwen3-30B-A3B experts 1.81 B active params of 3.04 B
for name, E, K, exp_share in [("Qwen3-30B-A3B", 128, 8, 48 * 8 * 3 * 2048 * 768 / 3.042e9),
                              ("gpt-oss-120b", 128, 4, 3.583 / 5.131), ("gpt-oss-20b", 32, 4, 2.389 / 3.607),
                              ("Qwen3.6-35B-A3B (+1 shared)", 256, 8, None)]:
    U = lambda k: E * (1 - (1 - K / E) ** k)
    cells = " | ".join(f"{U(k):.1f}" for k in (1, 2, 4, 8))
    if exp_share:
        r4 = (1 - exp_share) + exp_share * U(4) / K
        r8 = (1 - exp_share) + exp_share * U(8) / K
        print(f"| {name} | {E} | {K} | {cells} | {r4:.2f} | {r8:.2f} |")
    else:
        print(f"| {name} | {E} | {K} | {cells} | n/a | n/a |")
print("\nDense model: bytes(k)/bytes(1) = 1.00 for all k <= k* (only KV/activations grow).")
